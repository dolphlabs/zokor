#!/bin/sh
# Writes cmd/zokor/templates.sl: every file under cmd/zokor/templates/, as
# slang string lists the `zokor new` / `zokor add` commands write out. The
# templates stay real files you can read and edit; this embeds them, since
# slang has no multi-line strings and the CLI must not depend on finding
# its templates on disk. CI runs `--check`, which fails when templates.sl
# is stale.
#
#   cmd/zokor/gen_templates.sh           rewrite cmd/zokor/templates.sl
#   cmd/zokor/gen_templates.sh --check   exit 1 if it is stale
set -eu

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="$ROOT/cmd/zokor/templates"
OUT="$ROOT/cmd/zokor/templates.sl"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT INT TERM

# One group: every file under templates/<group>, sorted, as Template values.
group() {
    name=$1
    printf '\nfn %s_templates() -> [Template] {\n    let out: [Template] = [];\n' "$name"
    (cd "$SRC/$name" && find . -type f | LC_ALL=C sort) | while read -r f; do
        rel=${f#./}
        printf '    push(out, Template { path: "%s", lines: [\n' "$rel"
        awk -v file="$name/$rel" '
            index($0, "${") { printf "%s:%d: \"${\" would be read as interpolation\n", file, NR > "/dev/stderr"; exit 3 }
            {
                s = $0
                gsub(/\\/, "\\\\", s)
                gsub(/"/, "\\\"", s)
                gsub(/\t/, "\\t", s)
                if (NR > 1) printf ",\n"
                printf "        \"%s\"", s
            }
            END { printf "\n" }
        ' "$SRC/$name/$rel"
        printf '    ] });\n'
    done
    printf '    return out;\n}\n'
}

gen() {
    cat <<'HEAD'
// Generated by cmd/zokor/gen_templates.sh from cmd/zokor/templates/; do not
// edit. Change the template files and run `make templates`.

gc struct Template {
    path: str,
    lines: [str],
}
HEAD
    for g in project light_project feature pg_project pg_feature; do
        group "$g"
    done
}

gen > "$TMP"
if [ "${1:-}" = "--check" ]; then
    if ! cmp -s "$TMP" "$OUT"; then
        echo "FAIL cmd/zokor/templates.sl is stale: run make templates" >&2
        exit 1
    fi
    echo "PASS cmd/zokor/templates.sl is up to date"
    exit 0
fi
cp "$TMP" "$OUT"
echo "wrote cmd/zokor/templates.sl"
